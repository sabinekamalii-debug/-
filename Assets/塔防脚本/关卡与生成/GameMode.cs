/// <summary>
/// 开局流派倾向（取代原「地图生成模式」）。
/// 全游戏地图统一为混乱（仅打乱关卡顺序），本枚举只影响「初始流派倾向」——即抽卡时倾向出现哪类天赋卡：
///   守心模式：不改变抽卡权重，攻防守护均衡出现。
///   盛怒模式：放大攻击卡的抽取权重，更容易凑出进攻 build。
///   苟道模式：放大防御卡与守护卡的抽取权重，更容易凑出防守 build。
/// 倾向仅调整抽卡分布，不修改任何战斗数值，保证耐玩性来自构筑差异而非数值碾压。
/// </summary>
public enum GameMode
{
    Normal = 0,  // 守心模式（均衡抽卡）
    Fury = 1,    // 盛怒模式（攻击卡权重放大）
    Turtle = 2,  // 苟道模式（防御卡 + 守护卡权重放大）
}
