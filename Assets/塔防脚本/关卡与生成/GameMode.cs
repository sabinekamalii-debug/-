/// <summary>
/// 开局流派倾向（取代原「地图生成模式」）。
///
/// 设计背景：
/// 原游戏有「固定 / 混合 / 随机」三种地图生成模式，本意是防止固定关卡被反复游玩产生腻味感。
/// 但实测发现，纯关卡顺序的打乱对耐玩性贡献有限——玩家几把就能看穿只是同一套敌人提前/推后。
/// 真正决定耐玩性的是关卡内容多样性、局内构筑差异（天赋 / 卡牌 / 干员）与数值规则变化。
/// 因此决定：全游戏地图统一为「混乱模式」（仅打乱关卡顺序，不修改任何战斗数值），
/// 地图生成不再分模式；原「模式选择」入口改为「开局流派倾向」，只影响抽卡时哪类天赋卡更易出现。
///
/// 三种流派倾向：
///   守心模式：不改变抽卡权重，攻击 / 防御 / 守护三类卡均衡出现，标准体验。
///   盛怒模式：放大攻击卡的抽取权重，玩家更容易凑出纯进攻 build。
///   苟道模式：放大防御卡与守护卡的抽取权重，玩家更容易凑出防守 build。
///
/// 注意：流派倾向仅调整抽卡分布（见 RogueRuntimeState.GetCardTypeWeightMultiplier 与
/// GoldShopConfig.GetCardWeight），绝不修改任何战斗数值，保证耐玩性来自构筑差异而非数值碾压。
/// </summary>
public enum GameMode
{
    /// <summary>
    /// 守心模式（均衡抽卡）。
    /// 不改变任何抽卡权重，攻击 / 防御 / 守护三类天赋卡按基础概率均衡出现，是标准、无偏倚的体验。
    /// 旧存档未选择时回退到此模式。
    /// </summary>
    Normal = 0,  // 守心模式（均衡抽卡）

    /// <summary>
    /// 盛怒模式（进攻倾向）。
    /// 放大攻击卡（TalentCardType.Attack）的抽取权重（约 ×2.2），同时略降防御 / 守护卡权重（×0.7），
    /// 让玩家在商店与奖励选卡中更容易拿到进攻类卡，更快凑出纯输出 build。
    /// </summary>
    Fury = 1,    // 盛怒模式（攻击卡权重放大）

    /// <summary>
    /// 苟道模式（防守倾向）。
    /// 放大防御卡（TalentCardType.Defense）与守护卡（TalentCardType.Guardian）的抽取权重（均约 ×2.0），
    /// 同时略降攻击卡权重（×0.7），让玩家更容易拿到防守 / 续航类卡，凑出以守代攻的 build。
    /// </summary>
    Turtle = 2,  // 苟道模式（防御卡 + 守护卡权重放大）
}
